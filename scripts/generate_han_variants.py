"""Generate `domain/han_variants.py`: the characters only Simplified or only Traditional uses.

ADR-005: Lingua has one Chinese entry, so the bot decides the script from the characters. The
tables come from the Unicode Han database (`Unihan_Variants.txt`). A character is Simplified-only
if the database lists Traditional variants for it and it is none of them, and has no Simplified
variant of its own; Traditional-only is the mirror image. A character that is valid in both
scripts (such as 后 or 干) or that has both kinds of variant is in neither table. Only the common
CJK Unified Ideographs block (U+4E00 to U+9FFF) is kept.

Usage: python scripts/generate_han_variants.py [Unihan.zip | Unihan_Variants.txt]
Without an argument the database is downloaded from unicode.org. Run it when the Unicode
version should change, and commit the result.
"""

import sys
import tempfile
import textwrap
import urllib.request
import zipfile
from pathlib import Path

UNIHAN_URL = "https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip"
OUTPUT = (
    Path(__file__).resolve().parents[1] / "src" / "slack_translator" / "domain" / "han_variants.py"
)
FIRST, LAST = 0x4E00, 0x9FFF


def _characters(value: str) -> set[str]:
    return {chr(int(item.split("<")[0][2:], 16)) for item in value.split()}


def parse_variants(text: str) -> tuple[frozenset[str], frozenset[str]]:
    """The Simplified-only and Traditional-only characters of a `Unihan_Variants.txt` text."""
    traditional_of: dict[str, set[str]] = {}
    simplified_of: dict[str, set[str]] = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        code_point, field, value = line.split("\t", 2)
        if field == "kTraditionalVariant":
            traditional_of[chr(int(code_point[2:], 16))] = _characters(value)
        elif field == "kSimplifiedVariant":
            simplified_of[chr(int(code_point[2:], 16))] = _characters(value)

    def common(char: str) -> bool:
        return FIRST <= ord(char) <= LAST

    simplified_only = {
        char
        for char, variants in traditional_of.items()
        if char not in variants
        and (char not in simplified_of or char in simplified_of[char])
        and common(char)
    }
    traditional_only = {
        char
        for char, variants in simplified_of.items()
        if char not in variants
        and (char not in traditional_of or char in traditional_of[char])
        and common(char)
    }
    return frozenset(simplified_only), frozenset(traditional_only)


def render_module(simplified: frozenset[str], traditional: frozenset[str], source_note: str) -> str:
    def block(name: str, chars: frozenset[str]) -> str:
        body = "".join(sorted(chars))
        lines = "\n".join(
            f'    "{chunk}"' for chunk in textwrap.wrap(body, 40, break_on_hyphens=False)
        )
        return f"{name}: Final = frozenset(\n{lines}\n)\n"

    return (
        '"""Characters only Simplified or only Traditional Chinese uses (ADR-005).\n\n'
        "Generated by scripts/generate_han_variants.py from the Unicode Han database\n"
        f"(Unihan_Variants.txt, {source_note}). Do not edit by hand.\n"
        '"""\n\n'
        "from typing import Final\n\n"
        + block("SIMPLIFIED_ONLY", simplified)
        + "\n"
        + block("TRADITIONAL_ONLY", traditional)
    )


def _read(source: Path | None) -> str:
    if source is not None and source.suffix == ".txt":
        return source.read_text(encoding="utf-8")
    with tempfile.TemporaryDirectory() as folder:
        archive = source
        if archive is None:
            archive = Path(folder) / "Unihan.zip"
            urllib.request.urlretrieve(UNIHAN_URL, archive)
        with zipfile.ZipFile(archive) as bundle:
            return bundle.read("Unihan_Variants.txt").decode("utf-8")


def main(argv: list[str]) -> int:
    text = _read(Path(argv[0]) if argv else None)
    date = next((line.lstrip("# ").strip() for line in text.splitlines() if "Date:" in line), "")
    simplified, traditional = parse_variants(text)
    OUTPUT.write_text(
        render_module(simplified, traditional, date or "date unknown"), encoding="utf-8"
    )
    sys.stdout.write(
        f"{OUTPUT}: {len(simplified)} Simplified-only, {len(traditional)} Traditional-only\n"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
